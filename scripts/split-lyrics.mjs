// LCP phase 2: extract inline `lyrics: [...]` arrays out of src/data.ts into
// src/lyrics-static.ts (a lazy-loadable map) and strip them from data.ts — so the
// ~450KB of lyrics leaves the eager CLIENT bundle. String + bracket aware (lyrics
// contain '**[Verse 1]**'). Safe-by-default: dry-run unless `--write`.
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const WRITE = process.argv.includes('--write');
const ROOT = resolve(import.meta.dirname, '..');
const DATA = resolve(ROOT, 'src/data.ts');
const OUT = resolve(ROOT, 'src/lyrics-static.ts');
const src = readFileSync(DATA, 'utf8');

const map = {};
const spans = [];
let pos = 0;
const NEEDLE = 'lyrics: [';
while (true) {
  const at = src.indexOf(NEEDLE, pos);
  if (at < 0) break;
  const bracket = at + NEEDLE.length - 1;
  let depth = 0,
    j = bracket,
    inStr = false;
  for (; j < src.length; j++) {
    const c = src[j];
    if (inStr) {
      if (c === '\\') j++;
      else if (c === "'") inStr = false;
      continue;
    }
    if (c === "'") inStr = true;
    else if (c === '[') depth++;
    else if (c === ']') {
      depth--;
      if (depth === 0) break;
    }
  }
  let end = j + 1;
  if (src[end] === ',') end++;
  if (src[end] === '\n') end++;
  const lineStart = src.lastIndexOf('\n', at) + 1;
  const idChunk = src.lastIndexOf("id: '", at);
  const idMatch = /id: '([^']+)'/.exec(src.slice(idChunk, idChunk + 80));
  const id = idMatch ? idMatch[1] : `__unknown_${at}`;
  map[id] = src.slice(bracket, j + 1);
  spans.push([lineStart, end]);
  pos = end;
}

const ids = Object.keys(map);
const parsed = {};
for (const [id, arr] of Object.entries(map)) {
  // eslint-disable-next-line no-eval
  const lines = (0, eval)(arr);
  if (!Array.isArray(lines) || lines.some(l => typeof l !== 'string')) throw new Error(`parse failed for ${id}`);
  parsed[id] = lines;
}
const totalLines = Object.values(parsed).reduce((n, a) => n + a.length, 0);
console.log(`found ${spans.length} lyrics blocks / ${ids.length} ids / ${totalLines} lines`);

if (!WRITE) {
  console.log('dry-run (no --write): no files changed.');
  process.exit(0);
}

const body = ids
  .sort()
  .map(id => `  ${JSON.stringify(id)}: ${JSON.stringify(parsed[id])},`)
  .join('\n');
const header = `// AUTO-GENERATED by scripts/split-lyrics.mjs — the per-track lyric lines, split
// OUT of src/data.ts so they are NOT in the eager client bundle (LCP). The Worker
// imports this eagerly (SEO/tags); the client lazy-imports it (search + the
// loadLyrics fallback). To add/edit lyrics: edit here; data.ts holds only track
// metadata. Keep ids in sync with src/data.ts.\n\n`;
writeFileSync(OUT, `${header}export const STATIC_LYRICS: Record<string, string[]> = {\n${body}\n};\n`);

let stripped = src;
for (const [a, b] of spans.sort((x, y) => y[0] - x[0])) stripped = stripped.slice(0, a) + stripped.slice(b);
writeFileSync(DATA, stripped);
console.log(`WROTE ${OUT} (${ids.length} ids); data.ts ${src.length} → ${stripped.length} bytes (-${src.length - stripped.length})`);

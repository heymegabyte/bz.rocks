// Build step: precompute TRACK_TAGS into src/tags-static.ts so the CLIENT imports
// the result instead of deriving tags from lyrics at module-load (removes the
// eager 168×-regex derivation from boot + lets lyrics leave the client bundle).
// Run via tsx:  npx tsx scripts/gen-track-tags.mjs
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { TRACKS } from '../src/data.ts';
import { deriveTags } from '../src/tags-derive.ts';
import { STATIC_LYRICS } from '../src/lyrics-static.ts';

const ROOT = resolve(import.meta.dirname, '..');
const OUT = resolve(ROOT, 'src/tags-static.ts');

// Derive for every track, passing its lyrics (now in lyrics-static.ts, not on Track).
const entries = TRACKS.map(t => [t.id, deriveTags(t, STATIC_LYRICS[t.id] ?? [])]);
const obj = Object.fromEntries(entries);

const header = `// AUTO-GENERATED by scripts/gen-track-tags.mjs (npm run gen:tags). The precomputed
// semantic tags for every track — imported by the client/worker instead of
// deriving from lyrics at runtime. Regenerate whenever lyrics or the tag rules in
// src/tags-derive.ts change (tests/tags-derive.test.ts fails if this drifts).\n\n`;
const body = JSON.stringify(obj, null, 0);
writeFileSync(
  OUT,
  `${header}import type { TrackTags } from './tags';\n\nexport const STATIC_TAGS: Record<string, TrackTags> = ${body};\n`
);
console.log(`wrote ${OUT} — ${entries.length} tracks tagged`);
